-- 이모지 반응을 사용자별로 기록하는 테이블 추가 + 기존 count 0 데이터를 1로 변경 (PostgreSQL)
-- 수동 적용. 적용 순서:
--   개발: 이 SQL을 개발 DB에 먼저 실행 → 그다음 develop 머지(개발 서버 자동 배포)
--   운영: 이 SQL을 운영 DB에 먼저 실행 → 그다음 main 머지(운영 배포)
-- 테이블만 추가하므로 SQL을 먼저 적용해도 기존 앱 동작에는 영향이 없다. 여러 번 실행해도 결과가 같다.

BEGIN;

CREATE TABLE IF NOT EXISTS diary_emoji_reaction (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    diary_id   BIGINT       NOT NULL REFERENCES diary (id) ON DELETE CASCADE,
    member_id  BIGINT       NOT NULL,
    code       VARCHAR(64)  NOT NULL,
    created_at TIMESTAMP    NOT NULL,
    CONSTRAINT uq_diary_emoji_reaction UNIQUE (diary_id, member_id, code)
);

CREATE INDEX IF NOT EXISTS idx_diary_emoji_reaction_member ON diary_emoji_reaction (member_id, diary_id);

-- 예전에는 등록만 하고 count 0으로 저장했다. 등록 = 첫 반응으로 바뀌었으므로 1로 맞춘다.
-- (누가 등록했는지 기록이 없어 반응 행은 만들지 않는다. 기존 count는 그대로 유지된다.)
UPDATE diary_emoji SET count = 1 WHERE count = 0;

COMMIT;
